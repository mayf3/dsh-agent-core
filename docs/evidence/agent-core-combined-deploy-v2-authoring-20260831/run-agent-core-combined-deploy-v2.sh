fail() { echo "ERROR: $*" >&2; exit 2; }
hash_file() { "$GIT" -C "$REPO_ROOT" hash-object "$1"; }
line_at() { printf '%s\n' "$1" | /usr/bin/sed -n "${2}p"; }

write_manifest() {
  local root="$1" output="$2" path
  [ -d "$root" ] || return 1
  (
    cd "$root"
    /usr/bin/find . \( -path './node_modules' -o -path './bundle-*' -o -path './profile-*' \) -prune -o -type f -print \
      | /usr/bin/sed 's#^\./##' | LC_ALL=C /usr/bin/sort
  ) | while IFS= read -r path; do
    printf '%s  %s\n' "$(hash_file "$root/$path")" "$path"
  done > "$output"
}

verify_tree_status() {
  local root="$1" manifest count digest actual path expected i
  manifest="$(/usr/bin/mktemp "${TMPDIR:-/tmp}/ac-combined-manifest.XXXXXX")" || return 1
  if ! write_manifest "$root" "$manifest"; then /bin/rm -f "$manifest"; return 1; fi
  count="$(/usr/bin/wc -l < "$manifest" | /usr/bin/tr -d ' ')"
  digest="$("$SHASUM" -a 256 "$manifest" | /usr/bin/awk '{print $1}')"
  /bin/rm -f "$manifest"
  if [ "$count" = "$BASE_FILE_COUNT" ] && [ "$digest" = "$BASE_MANIFEST_SHA256" ]; then
    DETECTED_STATE="BASE"
    expected="$BASE_OIDS"
  elif [ "$count" = "$TARGET_FILE_COUNT" ] && [ "$digest" = "$TARGET_MANIFEST_SHA256" ]; then
    DETECTED_STATE="TARGET"
    expected="$TARGET_OIDS"
  else
    echo "ERROR: unapproved app manifest: count=$count sha256=$digest" >&2
    return 1
  fi
  i=1
  while [ "$i" -le "$DELTA_COUNT" ]; do
    path="$(line_at "$DELTA_PATHS" "$i")"
    if [ "$(line_at "$expected" "$i")" = "ABSENT" ]; then
      if [ "$DETECTED_STATE" = "BASE" ] && [ -e "$root/$path" ]; then
        echo "ERROR: new-file path already exists in BASE state: $path" >&2
        return 1
      fi
    else
      actual="$(hash_file "$root/$path")" || return 1
      [ "$actual" = "$(line_at "$expected" "$i")" ] || {
        echo "ERROR: delta path mismatch: $path state=$DETECTED_STATE expected=$(line_at "$expected" "$i") actual=$actual" >&2
        return 1
      }
    fi
    i=$((i + 1))
  done
  actual="$(hash_file "$root/$BREAKGLASS_PATH")" || return 1
  [ "$actual" = "$BREAKGLASS_OID" ] || {
    echo "ERROR: breakglass model-overrides drifted; refusing every write: expected=$BREAKGLASS_OID actual=$actual" >&2
    return 1
  }
  i=1
  while [ "$i" -le 2 ]; do
    path="$(line_at "$EXCLUDED_PIN_PATHS" "$i")"
    actual="$(hash_file "$root/$path")" || return 1
    [ "$actual" = "$(line_at "$EXCLUDED_PIN_OIDS" "$i")" ] || {
      echo "ERROR: excluded unauthorized drift file changed ($path expected=$(line_at "$EXCLUDED_PIN_OIDS" "$i") actual=$actual); this runner never writes it — re-audit required" >&2
      return 1
    }
    i=$((i + 1))
  done
}

