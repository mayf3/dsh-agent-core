run_apply() {
  local config_sha="$1"
  [ "$(/usr/bin/id -u)" = "0" ] || fail "--apply requires uid 0; runner never invokes sudo"
  [[ "$config_sha" =~ ^[0-9a-f]{64}$ ]] || fail "--apply takes the canary config sha256 printed by --check"
  validate_canary_prereqs
  [ "$CANARY_READY" = "YES" ] || fail "CANARY_PREREQS_READY=$CANARY_READY; apply refused (zero writes)"
  [ "$CANARY_CONFIG_SHA256" = "$config_sha" ] \
    || fail "canary config sha pin mismatch: reviewed=$config_sha actual=$CANARY_CONFIG_SHA256 (zero writes)"
  verify_source_authority
  verify_tree "$LIVE_ROOT" EITHER
  service_preflight
  if [ "$DETECTED_STATE" = "TARGET" ]; then
    echo "APPLY=NOOP_ALREADY_TARGET (zero files, zero reloads, zero canary mutation)"
    exit 0
  fi
  echo "Will durably install exactly $DELTA_COUNT files (7 modified + 2 new + bundle moderator config), pin the breakglass and both unauthorized drift files untouched, run the post-deploy workflow transition canary, then reload $SERVICE_LABEL exactly once on success."
  printf 'Type the phrase "%s" to proceed: ' "$CONFIRM_PHRASE"
  local answer=""; read -r answer
  [ "$answer" = "$CONFIRM_PHRASE" ] || fail "confirmation mismatch (zero writes)"

  local lock ts backup stage canary smoke path p mode uid gid actual i rc rollback_ok runner_sha
  lock="$TRUSTED_ROOT/.deploy-combined-v2.lock"
  ts="$(/bin/date -u +%Y%m%dT%H%M%SZ)"
  backup="$BACKUP_ROOT/agent-core-combined-v1-$ts"
  stage=""
  APPLY_WRITES=0; LOCK_CREATED=0; STAGE_CREATED=0; RESTART_COUNT=0
  /bin/mkdir "$lock" || fail "deploy lock exists: $lock"
  LOCK_CREATED=1; fsync_directory "$TRUSTED_ROOT"

  cleanup_apply() {
    rc="$1"; trap - EXIT; trap '' INT TERM; rollback_ok=1
    if [ "$rc" -ne 0 ] && [ "$APPLY_WRITES" = "1" ]; then
      echo "ERROR: apply failed (rc=$rc); durable rollback begins" >&2
      i=1
      while [ "$i" -le "$DELTA_COUNT" ]; do
        path="$(line_at "$DELTA_PATHS" "$i")"; p="$LIVE_ROOT/$path"
        if [ "$(line_at "$BASE_OIDS" "$i")" = "ABSENT" ]; then
          if [ -e "$p" ] || [ -L "$p" ]; then
            /bin/rm -f "$p" || rollback_ok=0
            fsync_directory "$(dirname "$p")" || rollback_ok=0
          fi
        else
          mode="$(/usr/bin/stat -f '%Lp' "$p" 2>/dev/null || echo 644)"
          uid="$(/usr/bin/stat -f '%u' "$p" 2>/dev/null || echo 0)"
          gid="$(/usr/bin/stat -f '%g' "$p" 2>/dev/null || echo 0)"
          atomic_install "$backup/$path" "$p" "$mode" "$uid" "$gid" || rollback_ok=0
        fi
        i=$((i + 1))
      done
      verify_tree_status "$LIVE_ROOT" && [ "$DETECTED_STATE" = "BASE" ] || rollback_ok=0
      if [ "$RESTART_COUNT" -gt 0 ]; then
        echo "NOTICE: rollback reload required after the success-path reload" >&2
        /bin/launchctl kickstart -k "$SERVICE_LABEL" && wait_for_health || rollback_ok=0
      fi
      if [ "$rollback_ok" = "1" ]; then
        echo "ROLLBACK=OK (all files and parents fsynced; BASE restored)"
      else
        echo "ERROR: ROLLBACK_INCOMPLETE backup=$backup lock=$lock" >&2
        exit 3
      fi
    fi
    [ "$STAGE_CREATED" = "0" ] || /bin/rm -rf "$stage" || rollback_ok=0
    if [ "$LOCK_CREATED" = "1" ]; then /bin/rmdir "$lock" || rollback_ok=0; fsync_directory "$TRUSTED_ROOT" || rollback_ok=0; fi
    [ "$rollback_ok" = "1" ] || exit 3
    exit "$rc"
  }
  trap 'cleanup_apply "$?"' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM

  /bin/mkdir -p "$backup"
  i=1
  while [ "$i" -le "$DELTA_COUNT" ]; do
    path="$(line_at "$DELTA_PATHS" "$i")"
    if [ "$(line_at "$BASE_OIDS" "$i")" != "ABSENT" ]; then
      /bin/mkdir -p "$backup/$(dirname "$path")"
      /bin/cp -p "$LIVE_ROOT/$path" "$backup/$path"
      actual="$(hash_file "$backup/$path")"
      [ "$actual" = "$(line_at "$BASE_OIDS" "$i")" ] || fail "backup mismatch: $path"
      fsync_file "$backup/$path"
      fsync_directory_chain "$backup/$(dirname "$path")" "$backup"
    fi
    i=$((i + 1))
  done
  runner_sha="$("$SHASUM" -a 256 "$0" | /usr/bin/awk '{print $1}')"
  cat > "$backup/README.txt" <<EOF
agent-core COMBINED deploy backup (Workflow delta + Forum moderation delta)
target_commit=$TARGET_COMMIT
transition_merge=$TRANSITION_MERGE
pagination_merge=$PAGINATION_MERGE
forum_merge=$FORUM_MERGE (impl head $FORUM_IMPL_HEAD)
base_manifest=$BASE_FILE_COUNT/$BASE_MANIFEST_SHA256
target_manifest=$TARGET_FILE_COUNT/$TARGET_MANIFEST_SHA256
delta_paths=$DELTA_COUNT (new files removed on rollback: packages/broker/src/capabilities/forum-moderation.js, packages/broker/src/error-detail-sanitizer.js)
breakglass=$BREAKGLASS_PATH@$BREAKGLASS_OID never-written
excluded_pinned=$(line_at "$EXCLUDED_PIN_PATHS" 1)@$(line_at "$EXCLUDED_PIN_OIDS" 1) $(line_at "$EXCLUDED_PIN_PATHS" 2)@$(line_at "$EXCLUDED_PIN_OIDS" 2) never-written
canary_config=$CANARY_CONFIG sha256=$CANARY_CONFIG_SHA256
runner=/tmp/run-agent-core-combined-deploy-v2.sh sha256=$runner_sha
created_utc=$ts
EOF
  fsync_file "$backup/README.txt"
  fsync_directory "$backup"
  fsync_directory "$BACKUP_ROOT"

  stage="$(/usr/bin/mktemp -d "$TRUSTED_ROOT/.deploy-combined-v2-stage.XXXXXX")"
  STAGE_CREATED=1; fsync_directory "$TRUSTED_ROOT"
  i=1
  while [ "$i" -le "$DELTA_COUNT" ]; do
    path="$(line_at "$DELTA_PATHS" "$i")"
    "$GIT" -C "$REPO_ROOT" show "$TARGET_COMMIT:$path" > "$stage/file-$i"
    [ "$(hash_file "$stage/file-$i")" = "$(line_at "$TARGET_OIDS" "$i")" ] || fail "staged blob mismatch: $path"
    fsync_file "$stage/file-$i"
    i=$((i + 1))
  done
  canary="$stage/canary.mjs"; write_canary_program "$canary"
  smoke="$stage/smoke.mjs"; write_smoke_program "$smoke"
  write_receipt_template "$stage/receipt.template"

  APPLY_WRITES=1
  i=1
  while [ "$i" -le "$DELTA_COUNT" ]; do
    path="$(line_at "$DELTA_PATHS" "$i")"; p="$LIVE_ROOT/$path"
    if [ "$(line_at "$BASE_OIDS" "$i")" = "ABSENT" ]; then
      atomic_install "$stage/file-$i" "$p" 644 0 0
    else
      mode="$(/usr/bin/stat -f '%Lp' "$p")"; uid="$(/usr/bin/stat -f '%u' "$p")"; gid="$(/usr/bin/stat -f '%g' "$p")"
      atomic_install "$stage/file-$i" "$p" "$mode" "$uid" "$gid"
    fi
    i=$((i + 1))
  done
  verify_tree "$LIVE_ROOT" TARGET

  echo "== post-deploy workflow transition canary against installed files (before the sole reload)"
  "$NODE" "$canary" "$LIVE_ROOT" "$CREDENTIALS_FILE" "$AUTH_ORIGIN" "$WORKFLOW_ORIGIN" "$CANARY_CONFIG" 2>&1 | /usr/bin/tee "$stage/canary.out"
  verify_tree "$LIVE_ROOT" TARGET

  echo "== sole success-path reload: $SERVICE_LABEL"
  RESTART_COUNT=1
  /bin/launchctl kickstart -k "$SERVICE_LABEL" || { echo "ERROR: runtime reload failed" >&2; exit 1; }
  [ "$RESTART_COUNT" = "1" ] || { echo "ERROR: reload count invariant violated" >&2; exit 1; }
  wait_for_health || { echo "ERROR: health failed after reload" >&2; exit 1; }
  /bin/launchctl print "$SERVICE_LABEL" >/dev/null 2>&1 || { echo "ERROR: launchd status failed" >&2; exit 1; }
  verify_tree "$LIVE_ROOT" TARGET

  echo "== post-reload combined smoke (workflow + forum normal + moderator visibility)"
  "$NODE" "$smoke" "$LIVE_ROOT" "$CREDENTIALS_FILE" "$AUTH_ORIGIN" "$CANARY_CONFIG" 2>&1 | /usr/bin/tee "$stage/smoke.out"
  verify_tree "$LIVE_ROOT" TARGET

  echo "== durable receipt"
  local canary_summary smoke_summary
  canary_summary="$(/usr/bin/grep -E '^[A-Z_]+=' "$stage/canary.out" | /usr/bin/tr '\n' ';' | /usr/bin/sed 's/;*$//')"
  smoke_summary="$(/usr/bin/grep -E '^[A-Z_]+=' "$stage/smoke.out" | /usr/bin/tr '\n' ';' | /usr/bin/sed 's/;*$//')"
  /usr/bin/sed -e "s#@RUNNER_SHA@#$runner_sha#" -e "s#@TS@#$(/bin/date -u +%Y-%m-%dT%H:%M:%SZ)#" \
    -e "s#@BACKUP@#$backup#" -e "s#@CANARY_SHA@#$CANARY_CONFIG_SHA256#" \
    -e "s#@CANARY_SUMMARY@#$canary_summary#" \
    -e "s#@SMOKE_SUMMARY@#$smoke_summary#" \
    "$stage/receipt.template" > "$backup/receipt.json"
  "$PYTHON3" - "$backup/receipt.json" <<'PY'
import json, sys
with open(sys.argv[1]) as fh:
    json.load(fh)
PY
  fsync_file "$backup/receipt.json"
  fsync_directory "$backup"
  printf '%s\n' "$(/bin/date -u +%Y-%m-%dT%H:%M:%SZ) applied target=$TARGET_COMMIT backup=$backup manifest=$TARGET_MANIFEST_SHA256 delta=combined-v2-9files canary=pass smoke=pass reload_count=1 breakglass=$BREAKGLASS_OID canary_config_sha256=$CANARY_CONFIG_SHA256 receipt=$backup/receipt.json" >> "$LEDGER"
  fsync_file "$LEDGER"; fsync_directory "$BACKUP_ROOT"
  # The durable receipt + ledger are the commit point. From here onward cleanup
  # failure must retain TARGET (and possibly its lock), never roll back into a
  # false receipt.
  APPLY_WRITES=0
  /bin/rm -rf "$stage"; STAGE_CREATED=0; fsync_directory "$TRUSTED_ROOT"
  /bin/rmdir "$lock"; LOCK_CREATED=0; fsync_directory "$TRUSTED_ROOT"
  trap - EXIT INT TERM
  echo "SUCCESS_COMMITTED target=$TARGET_COMMIT reload_count=1 breakglass_untouched=true excluded_drift_untouched=true"
  echo "BACKUP_PATH=$backup"
  echo "RECEIPT_PATH=$backup/receipt.json"
  echo "APPLY=PASS"
}

