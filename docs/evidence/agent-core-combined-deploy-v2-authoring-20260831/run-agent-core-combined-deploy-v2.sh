    i=$((i + 1))
  done
}

service_preflight() {
  local path p owner mode i=1
  [ -x "$PYTHON3" ] || fail "python3 unavailable"
  [ -x "$NODE" ] || fail "node unavailable: $NODE"
  [ ! -L "$LIVE_ROOT" ] || fail "live app root is a symlink"
  [ -f "$PLIST_PATH" ] || fail "launchd plist missing"
  [ -d "$BACKUP_ROOT" ] && [ ! -L "$BACKUP_ROOT" ] || fail "pre-existing backup root missing or symlinked: $BACKUP_ROOT"
  [ -f "$CREDENTIALS_FILE" ] && [ ! -L "$CREDENTIALS_FILE" ] || fail "credential store missing or symlinked"
  /bin/launchctl print "$SERVICE_LABEL" >/dev/null 2>&1 || fail "runtime service unavailable"
  /usr/bin/curl -fsS --max-time 3 "$HEALTH_URL" >/dev/null 2>&1 || fail "runtime unhealthy before deploy"
  while [ "$i" -le "$DELTA_COUNT" ]; do
    path="$(line_at "$DELTA_PATHS" "$i")"; p="$LIVE_ROOT/$path"
    if [ "$(line_at "$BASE_OIDS" "$i")" = "ABSENT" ]; then
      if [ -e "$p" ] || [ -L "$p" ]; then
        fail "new-file path already exists (unexpected state): $path"
      fi
    else
      [ -f "$p" ] && [ ! -L "$p" ] || fail "delta path is not a regular file: $path"
      owner="$(/usr/bin/stat -f '%u:%g' "$p")"; mode="$(/usr/bin/stat -f '%Lp' "$p")"
      [ "$owner" = "0:0" ] && [ "$mode" = "644" ] || fail "unexpected owner/mode: $path ($owner $mode)"
    fi
    i=$((i + 1))
  done
}

fsync_file() {
  "$PYTHON3" - "$1" <<'PY'
import os, sys
flags = os.O_RDONLY | (getattr(os, 'O_NOFOLLOW', 0))
fd = os.open(sys.argv[1], flags)
try: os.fsync(fd)
finally: os.close(fd)
PY
}

fsync_directory() {
  "$PYTHON3" - "$1" <<'PY'
import os, sys
flags = os.O_RDONLY | (getattr(os, 'O_DIRECTORY', 0))
fd = os.open(sys.argv[1], flags)
try: os.fsync(fd)
finally: os.close(fd)
PY
}

fsync_directory_chain() {
  # fsync_directory_chain <leaf-dir> <owned-stop-dir>, inclusive.
  local current="$1" stop="$2"
  case "$current/" in "$stop/"*) ;; *) return 1 ;; esac
  while :; do
    fsync_directory "$current" || return 1
    [ "$current" = "$stop" ] && break
    current="$(dirname "$current")"
  done
}

atomic_install() {
  local source="$1" target="$2" mode="$3" uid="$4" gid="$5" dir base tmp
  dir="$(dirname "$target")"; base="$(basename "$target")"; tmp="$dir/.${base}.combined-v2.$$"
  /usr/bin/install -m "$mode" -o "$uid" -g "$gid" "$source" "$tmp" || { /bin/rm -f "$tmp"; return 1; }
  fsync_file "$tmp" || { /bin/rm -f "$tmp"; return 1; }
  /bin/mv -f "$tmp" "$target" || { /bin/rm -f "$tmp"; return 1; }
  fsync_directory "$dir"
}

