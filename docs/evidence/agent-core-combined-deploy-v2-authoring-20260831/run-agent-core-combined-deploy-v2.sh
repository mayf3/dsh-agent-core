verify_source_authority() {
  local main actual path i
  [ -d "$REPO_ROOT/.git" ] || fail "repo checkout missing: $REPO_ROOT"
  "$GIT" -C "$REPO_ROOT" fetch github main >/dev/null 2>&1 \
    || fail "fresh github/main fetch failed"
  main="$("$GIT" -C "$REPO_ROOT" rev-parse github/main)"
  [ "$main" = "$TARGET_COMMIT" ] || fail "fresh main moved: expected=$TARGET_COMMIT actual=$main; re-audit required"
  "$GIT" -C "$REPO_ROOT" merge-base --is-ancestor "$TRANSITION_MERGE" "$main" \
    || fail "workflow_transition merge absent from fresh main"
  "$GIT" -C "$REPO_ROOT" merge-base --is-ancestor "$PAGINATION_MERGE" "$main" \
    || fail "pagination merge absent from fresh main"
  "$GIT" -C "$REPO_ROOT" merge-base --is-ancestor "$FORUM_IMPL_HEAD" "$main" \
    || fail "forum implementation head absent from fresh main"
