for (const key of ['agentId','domainId','canaryInstanceId','controlInstanceId','expectedAssigneePrincipalId','expectedCanaryTitle','transitionDefinitionId','expectedWorkflowStateVersion','expectedMinimumPages','expectedMinimumInstances']) {
  assert.ok(cfg[key] !== undefined && cfg[key] !== '', `missing canary config field: ${key}`)
}
